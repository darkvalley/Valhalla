/* Guards ComfyUI DOM layout contract introduced in Batch Text v1.6.0. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const file = path.resolve(__dirname,'../web/js/batch_text_inspector.js');
const text = fs.readFileSync(file,'utf8');
const compiled = text.replace(/^import .*;$/gm,'');
new vm.Script(compiled,{filename:'batch_text_inspector.js'});
assert.match(text,/node\.addDOMWidget\("preview", "customtext", panel/);
assert.match(text,/getMinHeight:\s*\(\)\s*=>\s*MIN_PREVIEW_HEIGHT/);
assert.match(text,/if\s*\(typeof widget\.computeLayoutSize === "function"/);
assert.match(text,/delete widget\.computeSize/);
assert.match(text,/node\.__batchIntegratedPreview = true/);
assert.match(text,/preview\.options\.getMinHeight = \(\) => MIN_PREVIEW_HEIGHT/);
assert.match(text,/delete preview\.options\.getMaxHeight/);
assert.match(text,/delete preview\.options\.getHeight/);
assert.match(text,/drawInfoIcon\(this, ctx\)/);
assert.match(text,/isInfoHit\(this, pos\)/);
assert.match(text,/function updatePreviewGeometry\(node, allowGrow = false\)/);
assert.match(text,/function updateVisibility\(node\)/);
assert.match(text,/setHidden\(node\.valhallaBatchLogDisplay, !writing\)/);
assert.match(text,/setHidden\(node\.valhallaBatchBrowseButton, !writing\)/);
assert.match(text,/setHidden\(node\.valhallaBatchPreviewWidget, !enabled\)/);
assert.match(text,/renderPreview\(this, payload\)/);
assert.match(text,/renderPreview\(node, detail\.output\)/);
assert.match(text,/Choose log folder\.\.\./);
assert.ok(!text.includes('Logmap kiezen...'),'Browse label must be English');
console.log('OK: v1.6.0 flexible DOM preview layout and inspector integration contract');
